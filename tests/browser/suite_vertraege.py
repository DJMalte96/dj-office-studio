"""Seit 1.13: Booking-Verträge, Vorlage, eigener Vertrag hochladen, Unterschrift.

Aus den Klick-Tests der jeweiligen Version übernommen; läuft über tests/browser/test_browser.py."""
from datetime import date, timedelta

SZENARIO = "111"


def lauf(pg, URL, ok, ENGINE, B, DATEIEN):
    shot = lambda pg, sel, name: ENGINE == "chromium" and pg.locator(sel).first.screenshot(path=f"{B}/{name}.png")
    def menue(pg, tab):
        pg.locator("#menu-dokumente .menu-kopf").click(); pg.wait_for_timeout(250)
        pg.locator(f"#menu-dokumente [data-tab={tab}]").click(); pg.wait_for_timeout(800)
    api = lambda pg, pfad: pg.evaluate(f"async () => (await fetch('api/{pfad}')).json()")
    pg.goto(URL); pg.wait_for_timeout(1800)
    if pg.locator("#tour-frage").is_visible(): pg.click("#tour-frage [data-frage=spaeter]"); pg.wait_for_timeout(300)
    ok("Menü Dokumente", pg.locator("#menu-dokumente .menu-kopf").is_visible())
    # Neuer Vertrag zu Angebot 012
    menue(pg, "vertrag-neu")
    ok("Auswahl mit Angeboten", pg.locator("#vt-wahl").is_visible() and pg.locator("[data-wahl-id]").count() >= 4)
    pg.fill("#vt-wahl-suche", "eva"); pg.wait_for_timeout(200)
    pg.locator("[data-wahl-id]").first.click(); pg.wait_for_timeout(1200)
    t = pg.inner_text("#vt-papier")
    ok("Vertrag aus Angebot", all(x in t for x in ("DJ-Vertrag", "Eva und Tom Probe", "17:00 bis 2:00 Uhr", "1.250,00 €", "375,00 €",
                                                   "§ 4 Verpflegung", "§ 7 Schäden durch Gäste", "§ 8 Schlussbestimmungen")))
    ok("Termin-Gruppe eingeklappt (aus Angebot)", not pg.locator("#vt-termin").evaluate("e => e.open") and "aus Angebot 012" in pg.inner_text("#vt-termin summary"))
    pg.fill("#vt-aufbau", "15:30"); pg.fill("#vt-kontakt", "Trauzeugin Lisa"); pg.fill("#vt-verpflegung", "für 2 Personen")
    pg.select_option("#vt-gema", "dj"); pg.wait_for_timeout(900)
    t = pg.inner_text("#vt-papier")
    ok("Felder gespeichert + Vorschau", "15:30 Uhr" in t and "Trauzeugin Lisa" in t and "(für 2 Personen)" in t and "übernimmt der DJ" in t)
    pg.locator(".vt-weitere summary").click(); pg.locator("#vt-schalter input[data-abschnitt=nebel]").check(); pg.wait_for_timeout(900)
    ok("Baustein zugeschaltet, rutscht hoch", "Nebel und Rauchmelder" in pg.inner_text("#vt-papier")
       and pg.locator(".vt-ab:not(.vt-weitere .vt-ab)", has_text="Nebel").count() == 1)
    pg.select_option("#vt-zahlung", "ganz"); pg.wait_for_timeout(800)
    ok("ohne Anzahlung", "Anzahlung von" not in pg.inner_text("#vt-papier") and not pg.locator("#vt-anz").is_visible())
    pg.select_option("#vt-zahlung", "rechnung"); pg.wait_for_timeout(800)
    pg.locator(".vt-einst").evaluate("e => e.scrollTop = 9999")
    ok("Senden sichtbar", pg.locator("[data-vt=senden]").is_visible())
    shot(pg, "#vertrag", "v1_vertrag")
    pg.click("[data-vt=senden]"); pg.wait_for_timeout(900)
    ok("Versand-Dialog für Vertrag", pg.locator("#versand").is_visible() and "Vertrag zu Angebot 012 senden" in pg.inner_text("#versand-titel"))
    pg.click("#versand-abbrechen"); pg.wait_for_timeout(200)
    r = pg.evaluate("async () => (await fetch('api/vertraege/1/pdf')).status")
    ok("PDF lädt", r == 200)
    pg.click("[data-vt=zu]"); pg.wait_for_timeout(800)
    # Vertrag ohne Angebot
    menue(pg, "vertraege")
    ok("Liste: 1 Vertrag", pg.locator("#vt-body tr[data-id]").count() == 1)
    pg.click("#vt-neu-knopf"); pg.wait_for_timeout(600)
    pg.click("[data-wahl=frei]"); pg.wait_for_timeout(1200)
    ok("ohne Angebot: Termin offen, V002", pg.locator("#vt-termin").evaluate("e => e.open") and "Vertrag V002" in pg.inner_text("#vt-titel"))
    pg.fill("#vf-name", "Anna Muster"); pg.wait_for_timeout(1000)
    ok(f"bekannter Kunde: Anschrift ({pg.input_value('#vf-strasse')})", pg.input_value("#vf-strasse") != "")
    pg.fill("#vf-anlass", "Geburtstagsfeier"); pg.fill("#vf-datum", "20.03.2027"); pg.locator("#vf-datum").press("Tab")
    pg.fill("#vf-von", "19:00"); pg.fill("#vf-bis", "01:00"); pg.fill("#vf-gage", "650"); pg.wait_for_timeout(1200)
    t = pg.inner_text("#vt-papier")
    ok("ohne Angebot gefüllt", all(x in t for x in ("Anna Muster", "Geburtstagsfeier", "20. März 2027", "19:00 bis 1:00 Uhr", "650,00 €", "195,00 €")))
    shot(pg, "#vertrag", "v2_ohne_angebot")
    pg.click("[data-vt=zu]"); pg.wait_for_timeout(900)
    ok("Liste: 2 Verträge", pg.locator("#vt-body tr[data-id]").count() == 2)
    pg.locator("#vt-body tr", has_text="V002").locator("[data-vt-act=verschickt]").click(); pg.wait_for_timeout(800)
    ok("als verschickt vermerkt", "verschickt" in pg.locator("#vt-body tr", has_text="V002").inner_text())
    pg.evaluate("showTab('start')"); pg.wait_for_timeout(1300)
    ok("Startseite: Vertrag nicht zurück", "1 Vertrag nicht unterschrieben zurück" in pg.inner_text("#start .wichtig"))
    pg.click("#start [data-start=vertraege]"); pg.wait_for_timeout(900)
    ok("→ Verträge", pg.locator("#tab-vertraege.active").count() == 1)
    # verschickt: gesperrt, wieder bearbeiten
    pg.locator("#vt-body tr", has_text="V002").locator("[data-vt-act=oeffnen]").first.click(); pg.wait_for_timeout(1000)
    ok("verschickt gesperrt", pg.locator("#vt-gesperrt").is_visible() and pg.locator("#vf-gage").is_disabled())
    pg.click("[data-vt=bearbeiten]"); pg.wait_for_timeout(900)
    ok("wieder bearbeitbar", not pg.locator("#vf-gage").is_disabled() and "Entwurf" in pg.inner_text("#vt-titel"))
    pg.click("[data-vt=zu]"); pg.wait_for_timeout(800)
    # Unterschrift mit Datei, Angebot annehmen
    pg.locator("#vt-body tr", has_text="Eva und Tom").locator("[data-vt-act=unterschrieben]").click(); pg.wait_for_timeout(400)
    pg.set_input_files("#vtu-datei", files=[{"name": "vertrag_zurueck.pdf", "mimeType": "application/pdf", "buffer": b"%PDF-1.4 zurueck"}])
    shot(pg, "#vt-unterschrift", "v3_unterschrift")
    pg.locator("#vtu-form button[type=submit]").click(); pg.wait_for_timeout(1000)
    zeile = pg.locator("#vt-body tr", has_text="Eva und Tom").inner_text()
    ok("unterschrieben mit Datei", "unterschrieben" in zeile and "vertrag_zurueck.pdf" in zeile)
    ang = next(a for a in api(pg, "angebote") if a["nummer"] == "012")
    ok("Angebot angenommen", ang["status"] == "angenommen")
    shot(pg, "#tab-vertraege", "v4_liste")
    # Vorlage: eigener Abschnitt, Upload, Anlage
    menue(pg, "vertragsvorlage")
    ok("Vorlage: 20 Bausteine", pg.locator("#vt-vorlage details").count() == 20)
    pg.click("#vt-eigen-neu"); pg.fill("#vt-ea-titel", "Dresscode"); pg.fill("#vt-ea-text", "Der DJ erscheint am {datum} bei {veranstalter}.")
    pg.click("[data-ea=speichern]"); pg.wait_for_timeout(800)
    ok("eigener Abschnitt", pg.locator("#vt-vorlage details").count() == 21 and "eigener Abschnitt" in pg.inner_text("#vt-vorlage"))
    pg.set_input_files("#vt-eigen-datei", f"{DATEIEN}/muster_vertrag.docx"); pg.wait_for_timeout(1500)
    ok("Word gelesen: 6 Abschnitte, 3 vorausgewählt", "6 Abschnitte erkannt" in pg.inner_text("#vt-eigen-ergebnis")
       and pg.locator("#vt-eigen-ergebnis [data-teil]:checked").count() == 3)
    pg.click("[data-eigen=uebernehmen]"); pg.wait_for_timeout(1200)
    ok("übernommen (24)", pg.locator("#vt-vorlage details").count() == 24 and "aus muster_vertrag.docx" in pg.inner_text("#vt-vorlage"))
    pg.set_input_files("#vt-eigen-datei", f"{DATEIEN}/AGB_Muster.pdf"); pg.wait_for_timeout(3000)
    ok("PDF gelesen (Kindprozess)", "Geltung" in pg.inner_text("#vt-eigen-ergebnis"))
    pg.evaluate("document.querySelectorAll('#vt-eigen-ergebnis [data-teil]').forEach(c => c.checked = false)")
    pg.check("#vt-eigen-anlage"); pg.click("[data-eigen=uebernehmen]"); pg.wait_for_timeout(1500)
    ok("Anlage", "AGB_Muster.pdf" in pg.inner_text("#vt-anlagen"))
    zeile = pg.locator("#vt-vorlage details", has_text="Dresscode"); zeile.locator("summary").click()
    zeile.locator("[data-v-hoch]").click(); pg.wait_for_timeout(800)
    vl = api(pg, "vertragsvorlage")["abschnitte"]
    ok("Reihenfolge gespeichert", [a["titel"] for a in vl].index("Dresscode") == 19)
    shot(pg, "#tab-vertragsvorlage", "v5_vorlage")
    menue(pg, "vertrag-neu"); pg.locator("[data-wahl-id]", has_text="Carla").click(); pg.wait_for_timeout(1200)
    t = pg.inner_text("#vt-papier")
    ok("neuer Vertrag: Dresscode mit Platzhaltern + Anfahrt + Anlage", f"Der DJ erscheint am {(date.today() + timedelta(days=30)):%d.%m.%Y} bei Carla Test." in t
       and "Anfahrt" in t and "AGB_Muster.pdf" in t)
    pg.click("[data-vt=zu]"); pg.wait_for_timeout(500)
    # Suche
    pg.keyboard.press("Control+k"); pg.wait_for_timeout(800); pg.keyboard.type("vertrag"); pg.wait_for_timeout(300)
    ok("Suche findet Verträge", "VERTRÄGE" in pg.inner_text("#suche-liste").upper())
    pg.keyboard.press("Escape")
    # Dunkel + Handy
    if ENGINE == "chromium":
        pg.evaluate("document.documentElement.dataset.theme = 'dark'")
        pg.evaluate("oeffneVertrag(1)"); pg.wait_for_timeout(1000); pg.locator("#vertrag").screenshot(path=f"{B}/v6_dunkel.png")
        pg.click("[data-vt=zu]"); pg.evaluate("document.documentElement.dataset.theme = 'light'")
    pg.set_viewport_size({"width": 390, "height": 844}); pg.evaluate("showTab('vertraege')"); pg.wait_for_timeout(800)
    ok(f"Handy-Breite {pg.evaluate('document.documentElement.scrollWidth')}", pg.evaluate("document.documentElement.scrollWidth") <= 392)
    pg.evaluate("oeffneVertrag(2)"); pg.wait_for_timeout(1000)
    ok("Handy: Vertrag offen, Senden sichtbar", pg.locator("[data-vt=senden]").is_visible())
