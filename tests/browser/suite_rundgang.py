"""Seit 1.12: Rundgang beim ersten Start und Schnellsuche.

Aus den Klick-Tests der jeweiligen Version übernommen; läuft über tests/browser/test_browser.py."""
SZENARIO = "111"


def lauf(pg, URL, ok, ENGINE, B, DATEIEN):
    shot = lambda pg, name: ENGINE == "chromium" and pg.screenshot(path=f"{B}/{name}.png")
    pg.goto(URL); pg.wait_for_timeout(2000)
    ok("Frage beim ersten Öffnen", pg.locator("#tour-frage").is_visible())
    shot(pg, "t0_frage")
    pg.click("#tour-frage [data-frage=los]"); pg.wait_for_timeout(600)
    n = pg.evaluate("document.querySelectorAll('.tour-punkte i').length")
    ok(f"Tour startet, {n} Schritte", pg.locator(".tour-karte").is_visible() and n == 13)
    shot(pg, "t1")
    for i in range(2, n + 1):
        pg.click(".tour-karte [data-tour=weiter]"); pg.wait_for_timeout(650)
        t = pg.inner_text(".tour-karte .tour-schritt")
        box = pg.evaluate("(() => { const k = document.querySelector('.tour-karte').getBoundingClientRect(); return [k.left, k.top, k.right, k.bottom, innerWidth, innerHeight]; })()")
        ok(f"Schritt {t}: Karte im Bild {[round(x) for x in box[:4]]}", t.startswith(f"{i} von") and box[0] >= 0 and box[1] >= 0 and box[2] <= box[4] and box[3] <= box[5])
        licht = pg.evaluate("(() => { const l = document.querySelector('.tour-licht'); return l.classList.contains('ohne') ? 'ohne' : l.getBoundingClientRect().height; })()")
        ok(f"   Licht: {licht}", licht == "ohne" or licht > 10)
        shot(pg, f"t{i}")
    pg.click(".tour-karte [data-tour=weiter]"); pg.wait_for_timeout(500)
    ok("Fertig: Tour weg, Startseite", pg.locator(".tour-karte").count() == 0 and pg.locator("#tab-start.active").count() == 1)
    pg.reload(); pg.wait_for_timeout(1800)
    ok("nach Reload keine Frage mehr", not pg.locator("#tour-frage").is_visible())
    # Einstellungen → Rundgang starten, Esc beendet
    pg.click("#einstellungen-btn"); pg.wait_for_timeout(700)
    pg.click(".eins-nav [data-thema=app]"); pg.wait_for_timeout(300)   # seit 1.16: Einstellungen nach Themen
    pg.click("#rundgang-starten"); pg.wait_for_timeout(600)
    ok("aus Einstellungen gestartet", pg.locator(".tour-karte").is_visible())
    pg.keyboard.press("ArrowRight"); pg.wait_for_timeout(500)
    ok("Pfeiltaste → Schritt 2", "2 von" in pg.inner_text(".tour-karte .tour-schritt"))
    pg.keyboard.press("Escape"); pg.wait_for_timeout(400)
    ok("Esc beendet", pg.locator(".tour-karte").count() == 0)
    # Schnellsuche
    pg.keyboard.press("Control+k"); pg.wait_for_timeout(800)
    ok("Strg+K öffnet Suche", pg.locator("#suche").is_visible())
    pg.keyboard.type("probe"); pg.wait_for_timeout(300)
    t = pg.inner_text("#suche-liste")
    ok("Suche 'probe': Rechnungen+Angebote+Kunden", "RECHNUNGEN" in t.upper() and "ANGEBOTE" in t.upper() and "KUNDEN" in t.upper())
    shot(pg, "s1_suche")
    pg.fill("#suche-eingabe", "012"); pg.wait_for_timeout(300)
    pg.keyboard.press("Enter"); pg.wait_for_timeout(900)
    ok("Enter öffnet Rechnung 012 (festgeschrieben → PDF) oder Editor", not pg.locator("#suche").is_visible())
    pg.keyboard.press("Escape"); pg.wait_for_timeout(300)
    pg.click("#suche-knopf"); pg.wait_for_timeout(800)
    pg.fill("#suche-eingabe", "eva hochzeit"); pg.wait_for_timeout(300)
    t = pg.inner_text("#suche-liste")
    ok(f"mehrere Wörter: {t[:80]!r}", "Angebot 012" in t)
    pg.keyboard.press("Enter"); pg.wait_for_timeout(900)
    ok("Angebot im Editor", pg.evaluate("state.modus") == "angebot" and pg.input_value("#r-nummer") == "012")
    pg.keyboard.press("Control+k"); pg.wait_for_timeout(700)
    pg.fill("#suche-eingabe", "beatport"); pg.wait_for_timeout(300)
    ok(f"Beleg gefunden: {pg.inner_text('#suche-liste')[:60]!r}", "BELEGE" in pg.inner_text("#suche-liste").upper())
    pg.fill("#suche-eingabe", "eür"); pg.wait_for_timeout(300)
    pg.keyboard.press("Enter"); pg.wait_for_timeout(900)
    ok("Seite EÜR geöffnet", pg.locator("#tab-euer.active").count() == 1)
    pg.keyboard.press("Control+k"); pg.wait_for_timeout(700)
    pg.fill("#suche-eingabe", "xyzxyz"); pg.wait_for_timeout(300)
    ok("nichts gefunden", "Nichts gefunden" in pg.inner_text("#suche-liste"))
    pg.keyboard.press("Escape")
    # Handy
    pg.set_viewport_size({"width": 390, "height": 844}); pg.evaluate("showTab('start')"); pg.wait_for_timeout(600)
    ok(f"Handy-Breite {pg.evaluate('document.documentElement.scrollWidth')}", pg.evaluate("document.documentElement.scrollWidth") <= 392)
    pg.evaluate("document.querySelector('#tour-frage').showModal()"); pg.wait_for_timeout(300); pg.click("#tour-frage [data-frage=los]"); pg.wait_for_timeout(600)
    for i in range(1, 13):
        box = pg.evaluate("(() => { const k = document.querySelector('.tour-karte').getBoundingClientRect(); return [k.left, k.top, k.right, k.bottom]; })()")
        ok(f"Handy Schritt {i}: Karte im Bild", box[0] >= 0 and box[1] >= 0 and box[2] <= 390 and box[3] <= 844)
        if ENGINE == "chromium" and i in (2, 6, 9): pg.screenshot(path=f"{B}/h{i}.png")
        pg.click(".tour-karte [data-tour=weiter]"); pg.wait_for_timeout(600)
    pg.keyboard.press("Escape")
