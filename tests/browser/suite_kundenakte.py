"""Seit 1.14: Vertrag → Rechnung, Bar bezahlt, Kundenakte, Jahres-Erinnerung, Abgelehnt.

Aus den Klick-Tests der jeweiligen Version übernommen; läuft über tests/browser/test_browser.py."""
SZENARIO = "114"


def lauf(pg, URL, ok, ENGINE, B, DATEIEN):
    shot = lambda pg, sel, name: ENGINE == "chromium" and pg.locator(sel).first.screenshot(path=f"{B}/{name}.png")
    api = lambda pg, pfad: pg.evaluate(f"async () => (await fetch('api/{pfad}')).json()")
    loesche = lambda pg, pfad: pg.evaluate(f"async () => (await fetch('api/{pfad}', {{method: 'DELETE', headers: SCHUTZ}})).status")
    wichtig = lambda pg: pg.inner_text("#start .wichtig")
    pg.goto(URL); pg.wait_for_timeout(2500)
    w = wichtig(pg)
    ok(f"Chips: {w!r}", "Rechnung schreiben: Feier Jonas" in w and "Anzahlung anfordern: Eva" in w and "Stammkunde Musikverein" in w
       and "✎ Schlussrechnung Jonas" not in w)
    ok("Angenommenes Angebot: Erinnerung nur für die frische Feier", "Feier Anna war am" in w and "Feier Lea" not in w)
    pg.click("[data-ka-start=angebot-rechnung]"); pg.wait_for_timeout(600)
    ok("Angebot: Frage Wie hat Anna bezahlt?", pg.locator("#rv-wahl").is_visible() and "Anna" in pg.inner_text("#rv-wahl-titel"))
    pg.click("[data-zahlweg=bar]"); pg.wait_for_timeout(600)
    ok("Angebot bar: 600 vorausgefüllt", pg.input_value("#bar-betrag") == "600" and "Angebot 015" in pg.inner_text("#bar-info"))
    pg.click("[data-bar=speichern]"); pg.wait_for_timeout(1500)
    ok("Angebot-Erinnerung nach Bar weg", "Feier Anna" not in wichtig(pg))
    for x in api(pg, "barzahlungen"): loesche(pg, f"barzahlungen/{x['id']}")
    pg.evaluate("renderStart()"); pg.wait_for_timeout(2000)
    pg.click("[data-ka-start=angebot-rechnung]"); pg.wait_for_timeout(600)
    pg.click("[data-zahlweg=rechnung]"); pg.wait_for_timeout(2000)
    ok("Angebot → Rechnung im Editor", "Aus Angebot 015" in pg.inner_text("#aus-angebot") and "Anna" in pg.input_value("#k-name"))
    pg.locator("#rechnung button[type=submit]").first.click(); pg.wait_for_timeout(2500); pg.keyboard.press("Escape")
    pg.evaluate("showTab('start')"); pg.wait_for_timeout(2000)
    ok("Angebot-Erinnerung nach Rechnung weg", "Feier Anna" not in wichtig(pg))
    ok("Start-Karte: Bar bezahlt neben → Rechnung", pg.locator("#start .start-karte [data-ka-start=bar]").count() >= 1)
    if ENGINE == "chromium": pg.screenshot(path=f"{B}/k1_start.png")

    # Jonas: Feier vorgestern, Anzahlung 025 bezahlt → „Wie hat … bezahlt?“ → bar
    pg.click("[data-ka-start=rechnung]"); pg.wait_for_timeout(600)
    ok("Frage: Wie hat Jonas bezahlt?", pg.locator("#rv-wahl").is_visible() and "Jonas" in pg.inner_text("#rv-wahl-titel"))
    shot(pg, "#rv-wahl", "q0_wahl")
    pg.click("[data-zahlweg=bar]"); pg.wait_for_timeout(600)
    ok("Bar bezahlt: Rest 630 vorausgefüllt", pg.input_value("#bar-betrag") == "630" and "Anzahlung 025" in pg.inner_text("#bar-info"))
    pg.fill("#bar-nr", "0347")
    shot(pg, "#bar-dialog", "q1_bar")
    pg.click("[data-bar=speichern]"); pg.wait_for_timeout(1500)
    bar = api(pg, "barzahlungen")
    ok("Barzahlung gespeichert (Vertrag, 630, Quittung 0347)", len(bar) == 1 and bar[0]["betrag"] == 630 and bar[0]["quittung_nr"] == "0347" and bar[0]["vertrag_id"])
    ok("Startseite: Jonas erledigt", "Feier Jonas" not in wichtig(pg))
    euer = api(pg, f"finanzen/euer?jahr={bar[0]['datum'][:4]}")
    ok("EÜR: Barzahlung zählt nicht", not any(z["id"] == "bar" for z in euer["einnahmen_zeilen"]))

    # zurück: Barzahlung löschen → Rechnung schreiben (Schlussrechnung)
    loesche(pg, f"barzahlungen/{bar[0]['id']}"); pg.evaluate("renderStart()"); pg.wait_for_timeout(2000)
    pg.click("[data-ka-start=rechnung]"); pg.wait_for_timeout(600)
    pg.click("[data-zahlweg=rechnung]"); pg.wait_for_timeout(2000)
    ok(f"Schlussrechnung: {pg.inner_text('#gesamt')}", "630," in pg.inner_text("#gesamt") and pg.locator("#rechnungsart-box [value=schluss]").is_checked())
    ok("Hinweis aus Vertrag", "Schlussrechnung aus Vertrag zu Angebot 010" in pg.inner_text("#aus-angebot"))
    pg.click("[data-rv-pos=verlaengerung]"); pg.wait_for_timeout(200)
    pg.keyboard.type("80"); pg.wait_for_timeout(400)
    ok(f"Verlängerung dazu: {pg.inner_text('#gesamt')}", "710," in pg.inner_text("#gesamt"))
    reihe = pg.evaluate("$$('#positionen .pos').map(p => [$('.beschreibung', p).value.slice(0, 12), $('.lieferdatum', p).value])")
    ok(f"Verlängerung vor dem Abzug, am Tag der Feier: {reihe}", reihe[1][0].startswith("Verlängerung") and reihe[1][1] == reihe[0][1]
       and reihe[2][0].startswith("abzüglich"))
    shot(pg, "#rechnung", "k2_schluss")
    pg.locator("#rechnung button[type=submit]").first.click(); pg.wait_for_timeout(2500); pg.keyboard.press("Escape")
    rs = [r for r in api(pg, "rechnungen") if r["rechnungsart"] == "schluss"]
    ok("Schlussrechnung am Vertrag gespeichert", len(rs) == 1 and rs[0]["gesamt"] == 710 and rs[0]["vertrag_id"])
    pg.evaluate("showTab('start')"); pg.wait_for_timeout(2000)
    ok("Jonas-Chip weg", "Feier Jonas" not in wichtig(pg))

    # Anzahlung aus Vertrag (Eva und Tom)
    pg.click("[data-ka-start=anzahlung]"); pg.wait_for_timeout(2000)
    ok(f"Anzahlung 30 %: {pg.inner_text('#gesamt')}", "375," in pg.inner_text("#gesamt") and pg.locator("#rechnungsart-box [value=anzahlung]").is_checked())
    pg.locator("#rechnung button[type=submit]").first.click(); pg.wait_for_timeout(2500); pg.keyboard.press("Escape")
    anz = [r for r in api(pg, "rechnungen") if r["rechnungsart"] == "anzahlung" and r["vertrag_id"]]
    ok("Anzahlungsrechnung am Vertrag", len(anz) == 1)
    pg.evaluate("showTab('start')"); pg.wait_for_timeout(2000)
    ok("Eva-Chip weg", "Anzahlung anfordern: Eva" not in wichtig(pg))

    # Verträge-Liste
    pg.evaluate("showTab('vertraege')"); pg.wait_for_timeout(1800)
    jonas, eva = pg.locator("#vt-body tr", has_text="Jonas").inner_text(), pg.locator("#vt-body tr", has_text="Eva").inner_text()
    ok(f"Jonas: Anzahlung + Rechnung: {jonas!r}", "Anzahlung 025 ✓ bezahlt" in jonas and "Rechnung" in jonas and "→ Rechnung" not in jonas)
    ok("Eva: Anzahlung offen, → Schlussrechnung, Bar bezahlt", "Anzahlung" in eva and "offen" in eva and "→ Schlussrechnung" in eva and "Bar bezahlt" in eva)
    ok("Name verlinkt zur Kundenakte", pg.locator("#vt-body [data-akte]").count() == 2)
    shot(pg, "#tab-vertraege", "k3_vertraege")
    pg.locator("#vt-body tr", has_text="Eva").locator("[data-vt-act=oeffnen]").first.click(); pg.wait_for_timeout(1500)
    ok("Vertragsfenster: → Rechnung im Kopf", pg.locator("#vt-zur-rechnung").is_visible())
    pg.click("#vt-zur-rechnung"); pg.wait_for_timeout(2000)
    ok("→ Rechnung aus dem Fenster = Schlussrechnung", pg.locator("#rechnungsart-box [value=schluss]").is_checked() and "Eva" in pg.input_value("#k-name"))

    # Angebote: Bar bezahlt oben bei den offenen (Verein → Hinweis)
    pg.evaluate("showTab('angebote')"); pg.wait_for_timeout(1500)
    ok("offene Angebote: Bar bezahlt neben → Rechnung", pg.locator("#angebote-offen [data-ka-bar]").count() >= 2)
    shot(pg, "#angebote-offen", "q2_angebote")
    pg.locator("#angebote-offen tr", has_text="Sportverein").locator("[data-ka-bar]").click(); pg.wait_for_timeout(800)
    ok("Vereins-Hinweis, 700 vorausgefüllt", "richtige Rechnung" in pg.inner_text("#bar-firma") and pg.input_value("#bar-betrag") == "700")
    pg.set_input_files("#bar-foto", files=[{"name": "durchschlag.png", "mimeType": "image/png", "buffer": b"\x89PNG\r\n\x1a\n" + b"\0" * 40}])
    pg.click("[data-bar=speichern]"); pg.wait_for_timeout(1800)
    zeile = pg.locator("#angebote-body tr", has_text="Sportverein")
    ok("Angebot: angenommen, bar bezahlt, kein → Rechnung", "bar bezahlt" in zeile.inner_text() and zeile.locator("[data-act=rechnung]").count() == 0
       and pg.locator("#angebote-offen tr", has_text="Sportverein").count() == 0)

    knoepfe = pg.locator("#angebote-offen tr", has_text="Anna Muster").first.locator("button").all_inner_texts()
    ok(f"Reihenfolge der Knöpfe: {knoepfe}", [k for k in knoepfe if k.strip()][-3:] == ["→ Rechnung", "Bar bezahlt", "Abgelehnt"])
    pg.locator("#angebote-offen tr", has_text="Carla").locator("[data-act=abgelehnt]").click(); pg.wait_for_timeout(1200)
    carla = [a for a in api(pg, "angebote") if a["kunde"]["name"] == "Carla Test"][0]
    ok("Abgelehnt: aus den offenen raus, Status abgelehnt", carla["status"] == "abgelehnt"
       and pg.locator("#angebote-offen tr", has_text="Carla").count() == 0)
    shot(pg, "#angebote-offen", "q3_abgelehnt")

    # Stammdaten → Kunden → Kundenakte
    pg.evaluate("showTab('kunden')"); pg.wait_for_timeout(1800)
    ok("Kunden: Kopfzeile + Stammkunde", "umsatz" in pg.inner_text("#tab-kunden thead").lower() and "Stammkunde" in pg.inner_text("#tab-kunden"))
    shot(pg, "#tab-kunden .card >> nth=1", "k4_kunden")
    pg.locator("#tab-kunden [data-akte]", has_text="Sportverein").click(); pg.wait_for_timeout(1200)
    t = pg.inner_text("#kundenakte")
    ok("Akte Sportverein: Bar mit Foto, Umsatz 700", "bar bezahlt" in t and "📎 Foto" in t and "700 €" in t)
    pg.click("#kundenakte [data-ka=zu]")
    pg.locator("#tab-kunden [data-akte]", has_text="Musikverein").click(); pg.wait_for_timeout(1200)
    t = pg.inner_text("#kundenakte")
    ok("Akte Musikverein: Stammkunde, Erinnerung", "Stammkunde" in t and "Letztes Jahr am" in t)
    shot(pg, "#kundenakte", "k5_akte")
    pg.click("[data-ka=diesmal]"); pg.wait_for_timeout(900)
    ok("Diesmal nicht: Hinweis weg, gespeichert", "Letztes Jahr am" not in pg.inner_text("#kundenakte")
       and api(pg, "kunden/erinnerung").get("musikverein beispiel", "").startswith("20"))
    pg.click("#kundenakte [data-ka=zu]")
    pg.evaluate("showTab('start')"); pg.wait_for_timeout(1800)
    ok("Startseite: kein Musikverein-Hinweis mehr", "Musikverein" not in wichtig(pg))
    pg.evaluate("fetch('api/kunden/erinnerung', {method: 'PUT', headers: {...SCHUTZ, 'Content-Type': 'application/json'}, body: JSON.stringify({name: 'Musikverein Beispiel', ruhe: null})})")
    pg.reload(); pg.wait_for_timeout(2500)
    ok("nach Wieder-Einschalten wieder da", "Stammkunde Musikverein" in wichtig(pg))
    pg.click("[data-ka-start=ruhe]"); pg.wait_for_timeout(1500)
    ok("✕ auf der Startseite blendet aus", "Musikverein" not in wichtig(pg))
    pg.evaluate("oeffneAkte('Musikverein Beispiel')"); pg.wait_for_timeout(1200)
    pg.evaluate("erinnerungRuhe('Musikverein Beispiel', null).then(() => oeffneAkte('Musikverein Beispiel'))"); pg.wait_for_timeout(1200)
    pg.click("[data-ka=nie]"); pg.wait_for_timeout(900)
    ok("Nicht mehr erinnern: Hinweis + Wieder einschalten", "Jahres-Erinnerung für diesen Kunden ist aus" in pg.inner_text("#kundenakte"))
    shot(pg, "#kundenakte", "k6_akte_aus")
    pg.click("[data-ka=wieder-an]"); pg.wait_for_timeout(900)
    ok("wieder eingeschaltet", "Letztes Jahr am" in pg.inner_text("#kundenakte"))
    pg.click("[data-ka=wieder]"); pg.wait_for_timeout(1200)
    ok("Angebot wie letztes Jahr im Editor", pg.evaluate("state.modus") == "angebot" and "Musikverein" in pg.input_value("#k-name")
       and "Firmenfeier" in pg.locator("#positionen .beschreibung").first.input_value())

    # Akte aus Archiv und Suche
    pg.evaluate("showTab('liste')"); pg.wait_for_timeout(1500)
    pg.locator("#liste-body [data-akte]").first.click(); pg.wait_for_timeout(1200)
    ok("Akte aus dem Archiv", pg.locator("#kundenakte").is_visible())
    pg.locator("#kundenakte tr[data-i]").first.click(); pg.wait_for_timeout(1000)
    ok("Eintrag öffnet sich", not pg.locator("#kundenakte").is_visible())
    pg.keyboard.press("Escape")
    pg.keyboard.press("Control+k" if ENGINE != "webkit" else "Meta+k"); pg.wait_for_timeout(600)
    if pg.locator("#suche").is_visible():
        pg.keyboard.type("Lea Pro"); pg.wait_for_timeout(900)
        pg.locator(".suche-treffer", has_text="Lea Probe").filter(has_text="Rechnungen").first.click()
        pg.wait_for_timeout(1200)
        ok("Suche → Kunde → Kundenakte", pg.locator("#kundenakte").is_visible() and "Lea Probe" in pg.inner_text("#kundenakte"))
        pg.click("#kundenakte [data-ka=zu]")
    else:
        ok("Suche öffnet sich", False)

    pg.set_viewport_size({"width": 390, "height": 844}); pg.evaluate("showTab('kunden')"); pg.wait_for_timeout(1200)
    ok(f"Handy-Breite {pg.evaluate('document.documentElement.scrollWidth')}", pg.evaluate("document.documentElement.scrollWidth") <= 392)
    pg.evaluate("oeffneAkte('Lea Probe')"); pg.wait_for_timeout(1200)
    ok(f"Akte auf dem Handy {pg.evaluate('document.documentElement.scrollWidth')}", pg.evaluate("document.documentElement.scrollWidth") <= 392)
    if ENGINE == "chromium": pg.screenshot(path=f"{B}/k7_handy.png")
